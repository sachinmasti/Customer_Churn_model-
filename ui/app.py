def build_payload(age, gender, location, email, tenure_months, monthly_charges,
                  total_charges, contract_type, internet_service, phone_service,
                  online_security, tech_support, payment_method,
                  satisfaction_score, support_tickets, last_contact_date):
    return {
        "age": int(age),
        "gender": gender.lower(),
        "location": location.lower(),
        "email": str(email).strip(),
        "tenure_months": float(tenure_months),
        "monthly_charges": float(monthly_charges),
        "total_charges": float(total_charges),
        "contract_type": contract_type.lower(),
        "internet_service": internet_service.lower(),
        "phone_service": phone_service.lower(),
        "online_security": online_security.lower(),
        "tech_support": tech_support.lower(),
        "payment_method": payment_method.lower(),
        "satisfaction_score": float(satisfaction_score),
        "support_tickets": int(support_tickets),
        "last_contact_date": last_contact_date.isoformat()
        if isinstance(last_contact_date, date) else str(last_contact_date),
    }


def render_result(label, confidence):
    churn_prob = confidence if label == "yes" else round(1 - confidence, 4)

    if label == "yes":
        card_cls, emoji, dot_cls = "result-risk", "⚠️", "risk"
        title = "High Churn Risk"
        sub = "This customer is likely to LEAVE — retention action recommended."
        fill_cls = "conf-fill risk"
    else:
        card_cls, emoji, dot_cls = "result-safe", "✅", "safe"
        title = "Customer Likely to Stay"
        sub = "Low churn probability — customer looks satisfied and loyal."
        fill_cls = "conf-fill"

    pct = int(round(churn_prob * 100))
    return f"""
    <div class="result-card {card_cls}">
        <div class="result-emoji">{emoji}</div>
        <div class="result-title">
            <span class="pulse-dot {dot_cls}"></span>{title}
        </div>
        <div class="result-sub">{sub}</div>
        <div class="conf-wrap">
            <div class="{fill_cls}" style="width: {pct}%"></div>
        </div>
        <div class="conf-label">Churn probability&nbsp;·&nbsp;{churn_prob*100:.1f}%</div>
    </div>
    """


def predict_churn(age, gender, location, email, tenure_months, monthly_charges,
                  total_charges, contract_type, internet_service, phone_service,
                  online_security, tech_support, payment_method,
                  satisfaction_score, support_tickets, last_contact_date):
    payload = build_payload(age, gender, location, email, tenure_months,
                            monthly_charges, total_charges, contract_type,
                            internet_service, phone_service, online_security,
                            tech_support, payment_method, satisfaction_score,
                            support_tickets, last_contact_date)
    try:
        resp = requests.post(PREDICT_ENDPOINT, json=payload, timeout=30)
    except requests.exceptions.ConnectionError:
        return ("🔴 **Cannot reach the prediction API.**\n\n"
                "Start it first:\n```\nuvicorn app:app --reload\n```")
    except requests.exceptions.Timeout:
        return "⏱️ **The API took too long to respond.** Please try again."

    if resp.status_code != 200:
        detail = resp.json().get("detail", resp.text) if resp.headers.get(
            "content-type", "").startswith("application/json") else resp.text
        return f"❌ **API error ({resp.status_code}):**\n\n{detail}"

    data = resp.json()
    return render_result(data["label"], float(data["confidence"]))

