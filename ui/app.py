def _histogram_payload(values):
    import numpy as np
    counts, edges = np.histogram(values, bins=40)
    mids = ((edges[:-1] + edges[1:]) / 2).round(3)
    return {"mids": mids.tolist(), "counts": counts.tolist()}


@functools.lru_cache(maxsize=1)
def get_insights():
    """Return the Insights-dashboard payload as a plain dict.

    Fast path : ui/insights.json, precomputed by scripts/export_insights.py
                -> renders instantly even on cold free-tier containers.
    Fallback  : full computation (pandas/sklearn/joblib); result is written
                back to ui/insights.json so subsequent loads stay fast.
    """
    if INSIGHTS_JSON.exists():
        return json.loads(INSIGHTS_JSON.read_text(encoding="utf-8"))
    payload = _compute_insights()
    try:
        INSIGHTS_JSON.write_text(json.dumps(payload), encoding="utf-8")
    except OSError:
        pass
    return payload


def _compute_insights():
    import joblib
    import pandas as pd
    from sklearn.model_selection import train_test_split
    from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                                 f1_score, confusion_matrix)

    df = pd.read_csv(DATA_PATH)
    model = joblib.load(MODEL_PATH)

    x = df.drop("churn", axis=1)
    y = df["churn"]

    _, x_test, _, y_test = train_test_split(x, y, test_size=0.2,
                                            random_state=42, shuffle=True)
    y_pred = model.predict(x_test)

    metrics = {
        "Accuracy":  accuracy_score(y_test, y_pred),
        "Precision": precision_score(y_test, y_pred, pos_label="yes"),
        "Recall":    recall_score(y_test, y_pred, pos_label="yes"),
        "F1 Score":  f1_score(y_test, y_pred, pos_label="yes"),
    }
    cm = confusion_matrix(y_test, y_pred, labels=["no", "yes"])

    # ---- feature importance from XGBoost estimators inside BaggingClassifier
    try:
        pre = model.named_steps["processors"]
        bag = model.named_steps["model"]
        all_cols = [str(c) for c in x.columns]

        def safe_out(trans):
            """Fit-time feature names, tolerating mid-pipeline
            FunctionTransformers that break sklearn's naming chain."""
            candidates = []
            if hasattr(trans, "steps"):
                candidates.extend(step for _, step in reversed(trans.steps))
            for step in candidates:
                try:
                    return step.get_feature_names_out()
                except Exception:
                    continue
            raise ValueError("no step provides feature names")

        def transformer_names(ct):
            names = []
            for name, trans, cols in ct.transformers_:
                if trans == "drop":
                    continue
                col_list = [str(c) for c in (cols if isinstance(cols, (
                    list, tuple, pd.Index)) else [cols])]
                if name == "remainder":          # may be positional indices
                    names.extend(
                        all_cols[int(c)] if str(c).isdigit() else c
                        for c in col_list)
                    continue
                try:
                    out = [str(n).split("__")[-1] for n in safe_out(trans)]
                    # pipelines fitted without DataFrame column names emit
                    # generic x0, x1_cat labels — decode via first step's
                    # own fit-time feature list.
                    first = (trans.steps[0][1]
                             if hasattr(trans, "steps") else trans)
                    try:
                        fit_inputs = [str(n).split("__")[-1] for n in
                                      first.get_feature_names_out()]
                    except Exception:
                        fit_inputs = []
                    pretty = []
                    for n in out:
                        m = _regex.match(r"^x(\d+)(?:_(.*))?$", n)
                        if m and fit_inputs and int(m.group(1)) < len(
                                fit_inputs):
                            base = fit_inputs[int(m.group(1))]
                            cat = m.group(2)
                            pretty.append(f"{base}_{cat}" if cat else base)
                        else:
                            pretty.append(n)
                    names.extend(pretty)
                except Exception:
                    names.extend(col_list)
            return names

        def humanize(n):
            n = n.strip().replace("_", " ")
            if n.endswith((" True", " False")):
                n = n.rsplit(" ", 1)[0]
            if "missingindicator" in n.lower():
                n = (n.replace("missingindicator", "").strip()
                      + " (was missing)")
            return n

        feat_names = [humanize(n) for n in transformer_names(pre)]
        imps = np.mean([est.feature_importances_ for est in bag.estimators_],
                       axis=0)
        if len(feat_names) != len(imps):
            raise ValueError("feature name/importance length mismatch")

        imp_df = (pd.DataFrame({"feature": feat_names, "importance": imps})
                    .groupby("feature", as_index=False).sum()
                    .sort_values("importance", ascending=False).head(12))
        imp_df["importance"] /= imp_df["importance"].sum()
        imp_df = imp_df.iloc[::-1]
    except Exception:
        imp_df = pd.DataFrame({"feature": [], "importance": []})

    return {
        "metrics": {k: round(float(v), 4) for k, v in metrics.items()},
        "confusion_matrix": cm.astype(int).tolist(),
        "feature_importance": imp_df.to_dict(orient="records"),
        "churn_counts": [
            {"label": "Retained",
             "count": int((df["churn"] == "no").sum())},
            {"label": "Churned",
             "count": int((df["churn"] == "yes").sum())},
        ],
        "histograms": {
            "age": _histogram_payload(df["age"].dropna().to_numpy()),
            "monthly_charges": _histogram_payload(
                df["monthly_charges"].dropna().to_numpy()),
            "tenure_months": _histogram_payload(
                df["tenure_months"].dropna().to_numpy()),
        },
        "meta": {"rows": int(len(df))},
    }


def metric_cards_html(metrics):
    cards = "".join(
        f'<div class="metric-card"><div class="metric-value">{v*100:.1f}%</div>'
        f'<div class="metric-name">{k}</div></div>'
        for k, v in metrics.items())
    return f'<div class="metric-row">{cards}</div>'


def _style(fig, height=330):
    """Transparent dark-glass Plotly styling."""
    fig.update_layout(
        template="plotly_dark",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font=dict(color="#cbd5e1", family="Inter, sans-serif"),
        title_font=dict(size=16, color="#e2e8f0"),
        margin=dict(t=54, b=18, l=18, r=18),
        height=height,
    )
    fig.update_xaxes(gridcolor="rgba(148,163,184,.15)", zeroline=False)
    fig.update_yaxes(gridcolor="rgba(148,163,184,.15)", zeroline=False)
    return fig


def donut_chart(churn_counts):
    colors = {"Churned": "#ef4444", "Retained": "#10b981"}
    fig = px.pie(churn_counts, names="label", values="count", hole=0.62,
                 color="label", color_discrete_map=colors,
                 title="Customer Churn Split")
    fig.update_traces(textinfo="percent+label",
                      textfont=dict(color="#e2e8f0"),
                      pull=[0.04, 0],
                      marker=dict(line=dict(color="rgba(0,0,0,0)", width=0)))
    return _style(fig)


def confusion_heatmap(cm):
    fig = go.Figure(go.Heatmap(
        z=cm, x=["Pred: No", "Pred: Yes"], y=["Actual: No", "Actual: Yes"],
        colorscale=[[0, "rgba(147,51,234,.15)"], [1, "#9333ea"]],
        showscale=False, xgap=4, ygap=4,
        text=cm, texttemplate="%{text}",
        textfont=dict(size=22, color="#ffffff")))
    fig.update_layout(title="Confusion Matrix",
                      yaxis=dict(autorange="reversed"))
    return _style(fig)


def importance_bar(imp_records):
    if not imp_records:
        fig = go.Figure()
        fig.update_layout(title="Feature Importance (unavailable)")
        return _style(fig, height=430)
    fig = go.Figure(go.Bar(
        x=[r["importance"] for r in imp_records],
        y=[r["feature"] for r in imp_records],
        orientation="h",
        marker=dict(color=[r["importance"] for r in imp_records],
                    colorscale="Purp", cornerradius=4)))
    fig.update_layout(title="Top Feature Importances")
    fig.update_yaxes(title=None)
    fig.update_xaxes(title=None)
    return _style(fig, height=430)


def distribution_fig(hist, title, color="#e879f9"):
    fig = go.Figure(go.Bar(
        x=hist["mids"], y=hist["counts"],
        marker_color=color, marker=dict(cornerradius=3),
        opacity=.9))
    fig.update_layout(title=title, bargap=0.04)
    return _style(fig, height=300)


